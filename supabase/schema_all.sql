-- 1. PRODUCTS TABLE
CREATE TABLE IF NOT EXISTS public.products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  category text NOT NULL,
  price numeric(10, 2) NOT NULL,
  "oldPrice" numeric(10, 2) DEFAULT 0,
  sizes text[] DEFAULT '{}'::text[],
  colors text[] DEFAULT '{}'::text[],
  fabric text DEFAULT '',
  stock integer DEFAULT 0,
  image text NOT NULL,
  images text[] DEFAULT '{}'::text[],
  description text DEFAULT '',
  rating numeric(3, 2) DEFAULT 0,
  "numReviews" integer DEFAULT 0,
  reviews jsonb DEFAULT '[]'::jsonb,
  "isActive" boolean DEFAULT true,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_products_category ON public.products (category);
CREATE INDEX IF NOT EXISTS idx_products_is_active ON public.products ("isActive");
CREATE INDEX IF NOT EXISTS idx_products_created_at ON public.products (created_at DESC);

ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.products TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.products_id_seq TO service_role;
GRANT SELECT ON TABLE public.products TO anon, authenticated;

DROP POLICY IF EXISTS "Allow public read access" ON public.products;
CREATE POLICY "Allow public read access" ON public.products FOR SELECT USING (true);


